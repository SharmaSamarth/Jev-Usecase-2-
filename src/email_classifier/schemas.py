"""Strict, provider-agnostic data models.

``ModelClassificationOutput`` is exactly what a model is asked to produce.
``EmailClassification`` is the normalized result every provider returns: the
model output plus fields the application owns (``email_id``,
``model_confidence``). ``email_id`` is never generated by a model, so it stays
identical across providers and reports.
"""

from __future__ import annotations

import re
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from .taxonomy import Action, Department, Intent, Tone, Urgency

MAX_RATIONALE_CHARS = 600
MAX_EVIDENCE_CHARS = 400
MAX_REVIEW_REASON_CHARS = 300


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class EmailInput(_Strict):
    """An email to classify. Contains no ground-truth information."""

    email_id: str = Field(min_length=1)
    subject: str = ""
    body: str

    @field_validator("email_id")
    @classmethod
    def _strip_id(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("email_id must not be blank")
        return value


class ModelClassificationOutput(_Strict):
    """The fields a model is asked to return."""

    tone: Tone
    urgency: Urgency
    department: Department
    intent: Intent
    recommended_action: Action
    human_review_required: bool
    review_reason: Optional[str] = None
    rationale: str = Field(min_length=1, max_length=MAX_RATIONALE_CHARS)
    evidence: str = Field(min_length=1, max_length=MAX_EVIDENCE_CHARS)

    @model_validator(mode="after")
    def _check_review_reason(self) -> "ModelClassificationOutput":
        reason = (self.review_reason or "").strip()
        if self.human_review_required and not reason:
            raise ValueError("review_reason is required when human_review_required is true")
        if len(reason) > MAX_REVIEW_REASON_CHARS:
            raise ValueError(f"review_reason exceeds {MAX_REVIEW_REASON_CHARS} characters")
        # A reason without a review flag carries no meaning; normalize it away.
        normalized = reason if self.human_review_required else None
        object.__setattr__(self, "review_reason", normalized)
        return self


class EmailClassification(_Strict):
    """Normalized classification returned by every provider.

    Labels are always required. ``rationale`` and ``evidence`` are optional
    because some providers (e.g. decision models such as Jev) return typed
    answers without generated text; they are ``None`` rather than invented.
    Text-generating providers validate them as required through
    ``ModelClassificationOutput`` before building this object.
    """

    email_id: str = Field(min_length=1)
    tone: Tone
    urgency: Urgency
    department: Department
    intent: Intent
    recommended_action: Action
    human_review_required: bool
    review_reason: Optional[str] = Field(default=None, max_length=MAX_REVIEW_REASON_CHARS)
    rationale: Optional[str] = Field(default=None, min_length=1, max_length=MAX_RATIONALE_CHARS)
    evidence: Optional[str] = Field(default=None, min_length=1, max_length=MAX_EVIDENCE_CHARS)
    model_confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0)

    @model_validator(mode="after")
    def _normalize_review_reason(self) -> "EmailClassification":
        if not self.human_review_required and self.review_reason is not None:
            object.__setattr__(self, "review_reason", None)
        return self

    @classmethod
    def from_model_output(
        cls,
        email_id: str,
        output: ModelClassificationOutput,
        model_confidence: Optional[float] = None,
    ) -> "EmailClassification":
        return cls(email_id=email_id, model_confidence=model_confidence, **output.model_dump())


class UsageInfo(_Strict):
    input_tokens: Optional[int] = None
    output_tokens: Optional[int] = None
    cache_creation_input_tokens: Optional[int] = None
    cache_read_input_tokens: Optional[int] = None

    def add(self, other: "UsageInfo") -> "UsageInfo":
        def _sum(a: Optional[int], b: Optional[int]) -> Optional[int]:
            if a is None and b is None:
                return None
            return (a or 0) + (b or 0)

        return UsageInfo(
            input_tokens=_sum(self.input_tokens, other.input_tokens),
            output_tokens=_sum(self.output_tokens, other.output_tokens),
            cache_creation_input_tokens=_sum(self.cache_creation_input_tokens, other.cache_creation_input_tokens),
            cache_read_input_tokens=_sum(self.cache_read_input_tokens, other.cache_read_input_tokens),
        )


class ClassificationResult(_Strict):
    """Outcome of one classification call, successful or not.

    Failures are first-class results so evaluation can account for them
    instead of silently dropping difficult emails.
    """

    email_id: str
    provider: str
    model: Optional[str] = None
    served_model: Optional[str] = None
    prompt_version: Optional[str] = None
    classification: Optional[EmailClassification] = None
    error_type: Optional[str] = None
    error_message: Optional[str] = None
    latency_ms: Optional[float] = None
    attempts: int = 0
    usage: Optional[UsageInfo] = None
    estimated_cost_usd: Optional[float] = None
    request_id: Optional[str] = None
    evidence_grounded: Optional[bool] = None
    #: True when the result was served from the local result cache (no API call
    #: in this run). Latency, usage, and cost then describe the original call.
    from_cache: bool = False

    @property
    def success(self) -> bool:
        return self.classification is not None

    @model_validator(mode="after")
    def _exactly_one_outcome(self) -> "ClassificationResult":
        if (self.classification is None) == (self.error_type is None):
            raise ValueError("a result must have either a classification or an error_type, not both")
        if self.classification is not None and self.classification.email_id != self.email_id:
            raise ValueError("classification.email_id does not match result email_id")
        return self


class GroundTruth(_Strict):
    tone: Tone
    urgency: Urgency
    department: Department
    intent: Intent
    recommended_action: Action
    human_review_required: bool


class LabeledEmail(_Strict):
    """An evaluation record. ``email`` is what providers see; ``expected`` never leaves the evaluator."""

    email: EmailInput
    expected: GroundTruth
    split: str = "test"
    notes: str = ""


_WS = re.compile(r"\s+")


def _normalize_for_match(text: str) -> str:
    text = text.lower().replace("’", "'").replace("“", '"').replace("”", '"')
    return _WS.sub(" ", text).strip().strip("\"'.…")


def evidence_is_grounded(evidence: str, email: EmailInput) -> bool:
    """True when the evidence excerpt appears in the email (case/whitespace-insensitive).

    Models sometimes join two fragments with an ellipsis; each fragment must
    then appear in the email.
    """
    haystack = _normalize_for_match(f"{email.subject}\n{email.body}")
    fragments = [f for f in re.split(r"\.\.\.|…", evidence) if _normalize_for_match(f)]
    return bool(fragments) and all(_normalize_for_match(f) in haystack for f in fragments)
